class Employee{
    constructor( name, salary, department){

        this.name = name;
        this.salary = salary;
        this.department = department;
    }
}

let emp1 = new Employee ("Chandan", 47000, "IT");


console.log("name :", emp1.name);
console.log("salary :", emp1.salary);
console.log("department :", emp1.department);

